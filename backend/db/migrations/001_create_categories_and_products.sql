-- SCRUM-42: PostgreSQL 17 product catalogue schema.
-- Apply once with psql -v ON_ERROR_STOP=1; seed data belongs in ../seeds/.
BEGIN;

CREATE TABLE categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    model VARCHAR(100) NOT NULL,
    serial_number VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    price NUMERIC(12, 2) NOT NULL,
    cost NUMERIC(12, 2),
    warranty_status VARCHAR(100) NOT NULL,
    distributor VARCHAR(255) NOT NULL,
    CONSTRAINT products_category_fk FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT products_serial_number_unique UNIQUE (serial_number),
    CONSTRAINT products_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT products_model_not_blank CHECK (btrim(model) <> ''),
    CONSTRAINT products_serial_number_not_blank CHECK (btrim(serial_number) <> ''),
    CONSTRAINT products_stock_nonnegative CHECK (stock_quantity >= 0),
    CONSTRAINT products_price_nonnegative CHECK (price >= 0 AND price <> 'NaN'::NUMERIC),
    CONSTRAINT products_cost_nonnegative CHECK (cost >= 0 AND cost <> 'NaN'::NUMERIC),
    CONSTRAINT products_warranty_status_not_blank CHECK (btrim(warranty_status) <> ''),
    CONSTRAINT products_distributor_not_blank CHECK (btrim(distributor) <> '')
);

CREATE INDEX products_category_id_idx ON products (category_id);

COMMENT ON COLUMN products.cost IS
    'Optional unit cost. Reports use 50% of the relevant sale price when NULL; preserve an explicit zero.';

COMMIT;
